// Un solo catálogo, sin ids repetidos (gana la primera aparición).
const byId = new Map()
for (const game of [
  ...casinoGames,
  ...casinoLiveGames,
  ...crashGameList,
  ...pokerGames,
  ...virtualGames,
  ...homeGames,
  ...extraGames,
]) {
  if (!byId.has(game.id)) byId.set(game.id, game)
}

export const GAME_CATALOG = [...byId.values()]

export function findGame(gameId) {
  return GAME_CATALOG.find((game) => game.id === gameId)
}

export default GAME_CATALOG
